# 리스트의 담긴 값의 갯수 변수에 저장
temps_length = len(temps)  # 변수에 4라는 값이 할당
print(temps_length)


# 리스트의 인덱스
print(temps[0], temps[-1])  # 가장 첫 번째 요소, 가장 마지막 요소
# -1을 사용하는 이유는 최신 값을 대체로 뒤에 추가가 됨
# 가장 최신 값은 결국 마지막 인덱스의 요소
# len 함수를 사용해서 리스트 길이 -1로 계산이 가능하지만
# 이 작업이 번거로워 -1을 가장 많이 사용

# 없는 인덱스 호출
# temps 리스트는 길이가 5

# print(temps[5]) -> IndexError: list index out of range 범위를 벗어난 값을 호출했기 때문이다.
# 인덱스 범위를 벗어나지 않도록 유의해줘야 한다.

print(f"temps[0]: {temps[0]}")
print(type(float_temps[0]))
