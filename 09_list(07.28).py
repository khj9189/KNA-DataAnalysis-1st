print("=== sort ===")

# sort -> 원본을 바꿔주기 때문에 .sort 가 된다
# 시계열 데이터의 특성을 살리고 싶으면 reverse를 사용해야 한다. sort 사용 불가
# sort: 오름차순 - 작은거에서 큰거 순서대로 정렬된다.
# -> 만약 내림차순으로 정렬하고 싶은 경우 reverse = True를 적으면 뒤집힌다. .sort(reverse = True)

n = [47, 2, 8, 100, 9, 1004, -1, 22]
print("n리스트 원본:", n)
n.sort()  # 원본 리스트가 수정되기에 바로 print안에 넣으면 none이 나온다.
print("n 리스트 오름차순 정렬 결과", n)

# 내림차순 정렬
n.sort(reverse=True)
print("n 리스트 내림차순 정렬 결과", n)

# ===========================================================================
print("=== reverse ===")
# 리스트 순서 뒤집기(정렬은 해주지 않음)
# .reverse()
# 뒤로 계속 쌓인 결과(최신)를 앞에서부터 보고싶을 때 사용
n = [47, 2, 8, 100, 9, 1004, -1, 22]
print("n리스트 원본:", n)

n.reverse()
print("n리스트 순서 뒤집기 결과:", n)

