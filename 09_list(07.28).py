# 리스트 값 추가
# .append(추가할 값)
# 리스트의 가장 마지막에 값을 추가
# 리스트 원본이 수정(재할당 필요 x)

nums = [1, 2, 3, 4, 5]
nums.append(999)
print(nums)

# 만약 원본 리스트와 특정 값을 추가한 리스트 둘 다 필요하다면
# 원본 리스트를 복사해서 리스트 수정 진행
# nums = [1,2,3,4,5] > 기존 리스트는 원본으로 봄
new_nums = nums  # 스스로의 메모리를 할당 받지 않고 주소만 복사해서 사용한다.
# 복사한 메모리 주소에 append를 했기 때문에 원본까지 영향을 받음

new_nums.append(111)
print("원본 nums 리스트:", nums)
print("복사본 new_nums에 111 append 결과:", new_nums)


# 이를 해결하기 위해서 .copy()라는 메서드를 사용
# new_nums2는 새로운 메모리에 nums 배열을 새로 저장
new_nums2 = nums.copy()
new_nums2.append(222)
print("원본 nums 리스트:", nums)
print("복사본 new_nums2에 222 append 결과:", new_nums2)

# .insert(위치, 값)
# 리스트에서 원하는 위치에 값을 삽입
# 원본 배열에 삽입된다.
# 기존 배열에서 삭제는 되지 않고, 해당하는 인덱스 값이 삽입(뒤에 요소들은 인덱스+1)
nums.insert(3, 333)
print(nums)

# .extend()
# 리스트 연결
# 다른 리스트의 값들을 풀어서 이어붙임
# A.expend(B)이면 A가 먼저 적히고 그 뒤에 B가 적힌다.

data = [1, 2, 3]
new_data = [7, 8, 9]
sum_data = data.extend(new_data)
print(sum_data)

# 또는 그냥 data.expend(new_data)라고 하고 print(data)라고 하면 된다.


#### 정리
# 오늘 꼮 알아야 하는 리스트 수정 메서드와 개념
# 리스트 수정 메서드:
# .append(추가할 값값): 리스트의 가장 마지막에 값을 추가가
# .insert(위치, 값): 첫 번째 인자인 위치 인덱스에 값을 삽입입
# .extend(합칠 리스트): 두 리스트를 하나의 리스트로 합체
# 위 세 가지 메서드들은 원본 리스트 자체를 수정


# 함수의 반환 개념을 안 뒤에 확인할 내용용
print(data.extend(new_data))
# 수정은 해주되 수정된 값을 보내주는 역할까지 수행하지는 않는다.
# 기대출력 결과: [1,2,3,7,8,9]
# 실제 결과: None
# extend() 메서드는 data라는 리스트를 '수정' 이를 반환하지 않음
# 반환값이 없어서 print 할 값이 없는 것 -> 그렇기에 변수에 할당해서 진행하면 된다.
print(data)


# 리스트를 수정하는 메서드는 모두 반환값이 없는가?
print(data.append(123))
print(data.insert(0, 123))
print(data.extend(new_data))

# a라는 변수에 넣으면 none이 나오는 이유: .append를 사용하면 값을 더한것은 맞음
# 그러나 append가 원래 값을 더한다는 기능만 수행해주기에 값을 다 더하면 다 더했음을 알려주기 위해
# none을 반환하게 된다.


