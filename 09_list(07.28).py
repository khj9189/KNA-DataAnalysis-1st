# 리스트 슬라이싱
# 리스트명[시작:끝:간격]
# 시작, 끝, 간격 인덱스는 모두 생략 가능(문자열과 동일)

temps = [35, 36, 37, 38]
print(temps[1:3])  # [36, 37]

p = 1, 2, 3, 4
print(p[1:3])  # 이런 경우에는 대괄호가 아닌 소괄호에 담겨 나온다.

print(temps[:2], temps[3:])  # 개별적으로 출력된다. 리스트가 2개가 나온다.

print(temps[::3])  # [35, 38] 첫 값은 나온다.

# 인덱싱 temps[0]은 값 하나(35)
# 슬라이싱 temps[0:2]은 리스트([35, 36])
# 슬라이싱은 영역을 잘라내는 역할이기 때문에 리스트를 반환하는 것

# temps[999]와 같이 없는 인덱스 사용 시 에러
# 슬라이싱은 "있는 만큼만" 잘라주기 때문에 에러 발생하지 않는다.

# 인덱스로 특정 값 바꾸기
# temps = [35, 36, 37, 38]

