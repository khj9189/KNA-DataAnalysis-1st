# list는 python의 자료형 중 하나
# 여러 개의 값을 [대괄호]에 감싸서 순서대로 저장한다.
# 나열된 값들은 자동으로 각자의 index 번호를 순서대로 가지게 된다.

# 변수 선언 시 s가 붙으면 리스트라고 추정이 가능하다.
temps = [35, 36, 37, 38]  # int 리스트
