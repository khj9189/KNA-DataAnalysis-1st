print("=== 쓰기모드로 파일을 새롭게 만들기 ===")

f = open("hello.txt", "w", encoding="utf-8")
# 파일 쓰기에 줄바꿈을 포함하려면 \n을 포함시킨다.
f.write("안녕하세요.\n")
# 파일 쓰기에 들여쓰기를 포함하려면 \t를 적으면 된다.
f.write("\t반갑습니다.\n")
f.close()

# ====================================================================
print("=== append로 파일에 내용을 추가하기 ===")

f = open("hello.txt", "a", encoding="utf-8")
# 파일 쓰기에 줄바꿈을 포함하려면 \n을 포함시킨다.
f.write("안녕하세요.\n")
# 파일 쓰기에 들여쓰기를 포함하려면 \t를 적으면 된다.
