# 항상 실행되지 않고 조건에 따라서 실행되는 코드가 달랐으면 할 때 사용
# 코드의 분기라고도 표현한다.
# 조건문의 조건은 True와 False로 결과가 나와야 한다.
# 들여쓰기 되어 있으면 if 문에 종속되어 있다는 의미이다.

# if 조건식:
#   실행할 코드(한 칸 들여쓰기: tab/ tab을 없애는 경우: shift + tab)

# if 문의 :은 그다음 올 코드가 if문 조건식 결과가 True일 때만 실행하라는 의미
# 들여쓰기 한 코드는 if문의 조건식 결과가 True일때 실행한다.
# 즉, 여기서부터 이 조건에 속한다라는 신호
# 조건에 속하는 코드는 모두 들여쓰기가 적용되어 있어야 한다.


temp = 85  # 측정 온도
if (
    temp < 80
):  # 만약 온도가 80을 넘으면 -> 조건을 나타내고 그 뒤부터는 실행 되어야 하는 것을 의미
    # 만약 temp라는 변수에 담긴 값이 80보다 크다면
    print(
        "temp 변수의 값이 80보다 크다"
    )  # 들여 쓴 이 줄 실행 -> 조건에 부합하지 않은 경우에는 출력이 되지 않는다.
    print("점검 요망")
print("측정 종료")  # if와 상관없이 항상 실행

