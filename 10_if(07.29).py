# else와 if만으로 분기하기에는 불편하고 if 중첩이 너무 많아져서 생겼다.

user_a = float(input("온도: "))

if user_a <= 36.2:
    print("당신은 저체온입니다. ")
elif user_a >= 36.9 and user_a < 37.8:
    print("당신은 미열입니다. 주의하세요.")
elif user_a >= 37.8:
    print("당신은 고온입니다. 병원에 방문하세요.")
else:
    print("당신은 정상체온입니다.")

print("정상체온입니다.")

